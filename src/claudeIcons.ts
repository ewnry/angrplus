export function getContextRingSvg(percent: number, size = 16, stroke = 2): string {
  const radius = (size - stroke) / 2;
  const circumference = 2 * Math.PI * radius;
  const clamped = Math.max(0, Math.min(100, percent));
  const offset = circumference - (clamped / 100) * circumference;
  const color = clamped > 80 ? '#e05252' : clamped > 50 ? '#d97757' : '#58a6ff';

  return `<svg width="${size}" height="${size}" viewBox="0 0 ${size} ${size}" class="agy-context-ring">
    <circle cx="${size / 2}" cy="${size / 2}" r="${radius}" fill="none" stroke="rgba(255, 255, 255, 0.15)" stroke-width="${stroke}"/>
    <circle cx="${size / 2}" cy="${size / 2}" r="${radius}" fill="none" stroke="${color}" stroke-width="${stroke}"
      stroke-dasharray="${circumference}" stroke-dashoffset="${offset}" stroke-linecap="round"
      transform="rotate(-90 ${size / 2} ${size / 2})"/>
  </svg>`;
}
